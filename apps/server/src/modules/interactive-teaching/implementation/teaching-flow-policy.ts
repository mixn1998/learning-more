import type { TeachingContextPackage } from '../ports/teaching-context-sources.js';

export function renderTeachingFlowPolicy(context: TeachingContextPackage): string {
  const state = context.teachingState;
  const phase = state.lessonPhase ?? 'warmup';
  const activePoint = context.lesson.coreKnowledgePoints.find(
    (point) => point.ref === state.activeKnowledgePointRef,
  );
  const lines =
    phase === 'warmup'
      ? context.turnKind === 'opening'
        ? [
            '当前阶段是课前热身。主动连接学习目标与已有经验，用一个容易回应的问题了解学习起点。',
            '不把热身问题写成整套知识问答。',
          ]
        : [
            '学习者正在回应课前热身。先自然回应其学习起点，然后进入账本标记的第一个知识点。',
            `本回合最多完成“${activePoint?.text ?? '第一个知识点'}”的讲解并发出一次非强制互动邀请，不要继续倾倒后续知识点，也不要在首次讲解当轮直接完成该知识点。`,
          ]
      : phase === 'knowledge_point'
        ? [
            `当前只负责知识点：${activePoint?.text ?? '账本标记的当前知识点'}。`,
            '可以自由选择解释、案例、类比、反驳或讨论方式；可以邀请学习者思考，但不规定唯一思考路径。学习者提出知识点框架内的其他有效思路时，沿其路径补足、纠偏并推进。',
            '讲解完成后可采用情境应用、对比辨析、错误诊断、条件变化预测或迁移判断等方式，给出一个综合、非强制的思考角度，但不强行要求学习者完成对应互动。',
            '邀请互动时不默认给出提示、解题路径或答案框架；只有学习者表现出困难或明确要求时，才提供适量支架。',
            '如果学习者正在响应互动，先回应其真实思路；没有新疑问或理解障碍时，用简短小结自然引入下一个知识点。若本轮暴露回答错误、误解或不理解，必须留在当前知识点改用新的解释、例子或思考角度，不得同时标记完成。',
            '如果学习者提出相关疑问，先解决疑问并留在当前知识点；如果学习者明确表示继续、不展开或跳过互动，则简短小结并进入下一节点。',
          ]
        : phase === 'comprehensive_application'
          ? [
              '全部知识点教学已经完成或由学习者明确跳过。当前进行一次跨知识点的综合应用。',
              '若尚未提出综合应用，只提出一个能够连接本课核心关系并具有迁移价值的任务；这是一项非强制应用邀请，学习者可以回答或明确跳过。',
              '若学习者回答，完成回应与反馈；回答不足时进行纠偏解释，但不再次追问同一应用任务。',
              '综合应用回应完成或被明确跳过后，用一小段话收束本次综合应用所连接的知识关系：说明这些关系如何共同支持一个判断、操作或迁移方法，再自然询问“对本课是否还有疑惑或其他讲解需求”。此时不要输出最终课程总结。',
            ]
          : phase === 'discussion'
            ? [
                '综合应用已经回应完成或被学习者明确跳过；当前处于讨论答疑阶段，等待学习者确认是否还有本课疑问或其他讲解需求。',
                '如果学习者提出疑问，完整回应并保持 lessonPhase=discussion、closureInquiry=awaiting_confirmation；在回复末尾再次自然询问是否还有其他疑惑或讲解需求，不要提前输出最终课程总结。',
                '用户可以连续追问任意轮次。只有学习者本轮明确表示没有疑问、不需要继续讲解或可以结束时，才输出结构完整、简洁连贯的最终课程总结，并在同一轮把状态设为 ready_to_close、confirmed_no_questions、delivered。',
              ]
            : phase === 'summary'
              ? [
                  '学习者已经明确表示没有其他疑问。当前只输出本课最终总结，概括核心知识、关系和本次学习形成的关键理解。',
                  '总结完成后告知学习者可以结束本课；不要再提出问题、布置任务或开启新的互动循环。',
                ]
              : [
                  '本课教学流程已经完成。简短回应当前诉求，并提示学习者可点击“结束本课”生成最终 Review。',
                ];
  const supplementalLines =
    phase === 'comprehensive_application'
      ? [
          '综合应用反馈结束时，用简短收束说明本次应用连接了哪些关键知识关系，以及这些关系共同形成了什么可迁移的方法或判断原则。不要写用户评价、掌握判断、流程宣布或未来学习建议，也不要求固定标题或模板句。',
          '用户没有直接回答或明确跳过综合应用时，仍需基于综合应用任务与已讲知识关系给出简短收束，但不要虚构用户表现或声称用户已经掌握。',
          '综合应用要连接本课全部核心知识点并体现跨知识点迁移，而不是复述或近义改写课堂中的互动。',
          '改变任务表征：可使用新情境决策、反例诊断、条件变化预测、比较取舍、解释陌生案例或开放式应用。不要沿用课堂原题的对象、数字、叙述骨架和问法。',
          '综合应用只提出一次；回答暴露缺口时直接纠偏解释，不再追加另一轮应用题。',
        ]
      : [];
  return `【当前教学阶段】\n${[...lines, ...supplementalLines].join('\n')}`;
}
